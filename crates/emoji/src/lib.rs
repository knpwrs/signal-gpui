//! Emoji data, search and type-ahead for the composer.
//!
//! The table and indexes are generated at build time from vendored
//! emojibase data (see `build.rs`). Search runs over an [`fst`] term index:
//! every shortcode, CLDR name, name word and keyword is a key, so a query is a
//! prefix range scan (plus a Levenshtein automaton for typo tolerance) with no
//! allocation proportional to the corpus beyond one score per emoji.

mod search;
mod typeahead;

use std::sync::LazyLock;

pub use search::{Match, SearchOptions, search, search_with_boost};
pub use typeahead::{Completion, completion_at, emoticon_replacement_at, jumbo_count, shortcode_replacement_at};

/// Emoji groups, in picker order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Group {
    SmileysEmotion,
    PeopleBody,
    Component,
    AnimalsNature,
    FoodDrink,
    TravelPlaces,
    Activities,
    Objects,
    Symbols,
    Flags,
}

impl Group {
    /// Groups shown in the picker (components are excluded from the table).
    pub const PICKER: [Group; 9] = [
        Group::SmileysEmotion,
        Group::PeopleBody,
        Group::AnimalsNature,
        Group::FoodDrink,
        Group::Activities,
        Group::TravelPlaces,
        Group::Objects,
        Group::Symbols,
        Group::Flags,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Group::SmileysEmotion => "Smileys & Emotion",
            Group::PeopleBody => "People & Body",
            Group::Component => "Components",
            Group::AnimalsNature => "Animals & Nature",
            Group::FoodDrink => "Food & Drink",
            Group::TravelPlaces => "Travel & Places",
            Group::Activities => "Activities",
            Group::Objects => "Objects",
            Group::Symbols => "Symbols",
            Group::Flags => "Flags",
        }
    }

    /// A representative emoji for the picker's group tabs.
    pub fn icon(self) -> &'static str {
        match self {
            Group::SmileysEmotion => "😀",
            Group::PeopleBody => "👋",
            Group::Component => "🏻",
            Group::AnimalsNature => "🐻",
            Group::FoodDrink => "🍔",
            Group::TravelPlaces => "✈️",
            Group::Activities => "⚽️",
            Group::Objects => "💡",
            Group::Symbols => "❤️",
            Group::Flags => "🏳️",
        }
    }
}

/// Fitzpatrick skin tone modifiers, light to dark.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SkinTone {
    Light,
    MediumLight,
    Medium,
    MediumDark,
    Dark,
}

impl SkinTone {
    pub const ALL: [SkinTone; 5] = [
        SkinTone::Light,
        SkinTone::MediumLight,
        SkinTone::Medium,
        SkinTone::MediumDark,
        SkinTone::Dark,
    ];

    fn index(self) -> usize {
        self as usize
    }
}

#[derive(Debug, PartialEq)]
pub struct Emoji {
    /// Index into [`all`].
    pub id: EmojiId,
    /// Fully-qualified glyph (with VS16 where applicable).
    pub glyph: &'static str,
    pub hexcode: &'static str,
    /// CLDR short name, e.g. "grinning face with sweat".
    pub name: &'static str,
    pub group: Group,
    /// Emoji version that introduced it, e.g. `15.1`.
    pub version: f32,
    /// Shortcodes without colons; iamcal (Signal / Slack style) first.
    pub shortcodes: &'static [&'static str],
    /// CLDR keywords.
    pub tags: &'static [&'static str],
    skins: Option<[&'static str; 5]>,
}

/// Index of an emoji in [`all`]. Stable for a given data version only.
pub type EmojiId = u16;

impl Emoji {
    pub fn supports_skin_tones(&self) -> bool {
        self.skins.is_some()
    }

    /// The glyph with `tone` applied, or the base glyph if the emoji has no
    /// skin tone variants.
    pub fn glyph_with(&self, tone: Option<SkinTone>) -> &'static str {
        match (tone, self.skins) {
            (Some(tone), Some(skins)) => skins[tone.index()],
            _ => self.glyph,
        }
    }

    pub fn skin_variants(&self) -> Option<&[&'static str; 5]> {
        self.skins.as_ref()
    }

    /// Primary shortcode, e.g. `"joy"`.
    pub fn shortcode(&self) -> Option<&'static str> {
        self.shortcodes.first().copied()
    }
}

include!(concat!(env!("OUT_DIR"), "/emoji_table.rs"));

static TERMS_FST: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/terms.fst"));
static SHORTCODES_FST: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/shortcodes.fst"));
static GLYPHS_FST: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/glyphs.fst"));

pub(crate) static TERMS: LazyLock<fst::Map<&'static [u8]>> =
    LazyLock::new(|| fst::Map::new(TERMS_FST).expect("terms.fst is generated by build.rs"));
static SHORTCODES: LazyLock<fst::Map<&'static [u8]>> =
    LazyLock::new(|| fst::Map::new(SHORTCODES_FST).expect("shortcodes.fst is generated by build.rs"));
static GLYPHS: LazyLock<fst::Map<&'static [u8]>> =
    LazyLock::new(|| fst::Map::new(GLYPHS_FST).expect("glyphs.fst is generated by build.rs"));

/// Every emoji, in picker order.
pub fn all() -> &'static [Emoji] {
    &EMOJI
}

pub fn get(id: EmojiId) -> Option<&'static Emoji> {
    EMOJI.get(id as usize)
}

/// Emoji in `group`, in picker order.
pub fn in_group(group: Group) -> impl Iterator<Item = &'static Emoji> {
    // The table is sorted by order, which is grouped, so this is a contiguous run.
    EMOJI.iter().filter(move |e| e.group == group)
}

/// Exact shortcode lookup, without colons: `by_shortcode("joy")`.
pub fn by_shortcode(code: &str) -> Option<&'static Emoji> {
    SHORTCODES.get(code).and_then(|id| get(id as EmojiId))
}

/// Finds an emoji by glyph, accepting skin-toned and unqualified forms.
/// Returns the base emoji and the tone that was applied.
pub fn by_glyph(glyph: &str) -> Option<(&'static Emoji, Option<SkinTone>)> {
    let packed = GLYPHS.get(glyph)?;
    let emoji = get((packed >> 8) as EmojiId)?;
    let tone = match packed & 0xff {
        0 => None,
        t => SkinTone::ALL.get(t as usize - 1).copied(),
    };
    Some((emoji, tone))
}

/// Initialize the lazily-parsed indexes, e.g. on a background thread at startup.
pub fn warm_up() {
    LazyLock::force(&TERMS);
    LazyLock::force(&SHORTCODES);
    LazyLock::force(&GLYPHS);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_populated() {
        assert!(all().len() > 1800);
        assert!(all().iter().all(|e| e.group != Group::Component));
    }

    #[test]
    fn ids_round_trip() {
        for (i, e) in all().iter().enumerate() {
            assert_eq!(e.id as usize, i);
        }
    }

    #[test]
    fn shortcode_lookup() {
        assert_eq!(by_shortcode("joy").unwrap().glyph, "😂");
        assert_eq!(by_shortcode("+1").unwrap().name, "thumbs up");
        assert_eq!(by_shortcode("thumbsup").unwrap().name, "thumbs up");
        assert!(by_shortcode("definitely_not_an_emoji").is_none());
    }

    #[test]
    fn glyph_lookup_handles_tones_and_qualification() {
        let (wave, tone) = by_glyph("👋🏽").unwrap();
        assert_eq!(wave.name, "waving hand");
        assert_eq!(tone, Some(SkinTone::Medium));

        let (heart, tone) = by_glyph("❤").unwrap();
        assert_eq!(heart.name, "red heart");
        assert_eq!(tone, None);
    }

    #[test]
    fn skin_tones() {
        let wave = by_shortcode("wave").unwrap();
        assert!(wave.supports_skin_tones());
        assert_eq!(wave.glyph_with(Some(SkinTone::Dark)), "👋🏿");
        let joy = by_shortcode("joy").unwrap();
        assert_eq!(joy.glyph_with(Some(SkinTone::Dark)), "😂");
    }

    #[test]
    fn groups_are_contiguous() {
        let mut seen = Vec::new();
        for e in all() {
            if seen.last() != Some(&e.group) {
                assert!(!seen.contains(&e.group), "{:?} is split", e.group);
                seen.push(e.group);
            }
        }
    }
}
